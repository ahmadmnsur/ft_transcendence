// Finds the physical (left/right) Tailwind v4 classes in a source folder.
// Used for docs/research/rtl-mirroring.md, section 1; kept for #146, which settles the rule.
//
// Usage: node physical-scan.mjs <dir>
//
// It splits every line of the .ts, .tsx and .css files under <dir> into tokens, the way
// Tailwind reads source files as plain text. It strips variant prefixes (`focus:`, `md:`)
// and a leading `!` or `-`, then reports each token that names a physical utility.
// A hit on a comment line is marked `(comment)`: most are prose (`right-aligns`), but a
// real class in a comment still generates CSS (`mr-auto` at `Modal.tsx:17`).
// The families with no flow-relative twin (`origin-`, gradient directions, `translate-x-`,
// `scale-x-`, `skew-x-`) are reported too, since they need an `rtl:` variant instead.
//
// It cannot see: classes generated by `@source inline()` with braces (`ml-{1..2}`), so it
// reports every `@source inline(` line for a person to read; and JavaScript that assumes
// left to right (`scrollLeft` math, arrow keys, inline `scaleX`).
//
// Exit code: 1 when a class is found outside a comment, or an `@source inline(` line exists;
// 0 otherwise.
import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2];
if (!root) {
  console.error('Usage: node physical-scan.mjs <dir>');
  process.exit(2);
}

const physical = [
  /^(m|p)[lr]-.+$/, // ml- mr- pl- pr-
  /^scroll-(m|p)[lr]-.+$/, // scroll-ml- scroll-pr- …
  /^(left|right)-.+$/, // left-4 right-px
  /^text-(left|right)$/,
  /^(float|clear)-(left|right)$/,
  /^border-[lr](-\d+|-\[.+\]|-(?!line)[a-z]+-\d+|-(?:line|line-strong|transparent|current)|)$/, // border-l, border-l-2, border-l-<colour>
  /^rounded-([lr]|[tb][lr])(-(none|xs|sm|md|lg|xl|2xl|3xl|4xl|full|\[.+\]))?$/,
  /^origin-(left|right|top-left|top-right|bottom-left|bottom-right)$/,
  /^bg-(linear|gradient)-to-(l|r|tl|tr|bl|br)$/,
  /^bg-(left|right)(-top|-bottom)?$/,
  /^object-(left|right)(-top|-bottom)?$/,
  /^translate-x-.+$/,
  /^scale-x-.+$/,
  /^skew-x-.+$/,
];

const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(entry.name)) files.push(p);
  }
})(root);

const hits = [];
const inlineSources = [];
for (const file of files.sort()) {
  const lines = fs.readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const where = `${path.relative(root, file)}:${i + 1}`;
    if (file.endsWith('.css') && line.includes('@source inline(')) inlineSources.push(`${where}\t${line.trim()}`);
    const comment = /^\s*(\/\/|\*|\/\*)/.test(line);
    for (const raw of line.split(/[\s"'`{}()$,;]+/)) {
      if (!raw) continue;
      const base = raw.split(':').pop().replace(/^!/, '').replace(/^-/, '');
      if (physical.some((re) => re.test(base))) hits.push({ where, raw, comment });
    }
  });
}

for (const h of hits) console.log(`${h.where}\t${h.raw}${h.comment ? '\t(comment)' : ''}`);
for (const s of inlineSources) console.log(`${s}\t(@source inline: read by hand)`);
const inCode = hits.filter((h) => !h.comment).length;
console.log(`\n${inCode} in code, ${hits.length - inCode} in comments, ${inlineSources.length} @source inline() lines`);
process.exit(inCode > 0 || inlineSources.length > 0 ? 1 : 0);

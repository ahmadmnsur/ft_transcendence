// Finds the physical (left/right) Tailwind v4 classes in a source folder.
// Used for docs/research/rtl-mirroring.md, section 1; kept for #146, which settles the rule.
// Widened on 2026-10-13 after Ahmad's review of 18e04ea (#140).
//
// Usage: node physical-scan.mjs web/src
//
// It reads the .ts, .tsx and .css files under the folder it is given as plain text, the way
// Tailwind reads source files (in CSS, Tailwind reads only `@apply` and `@source`, so a class in
// a CSS comment generates nothing). It cuts them into tokens at spaces, quotes, braces, `;`, `,`,
// `=`, `<`, `>` and `$`, but not inside `[…]`, so `bg-[linear-gradient(to_right,red,blue)]`
// stays whole. It strips variants at each `:` outside `[…]` and `(…)` (`md:hover:`,
// `has-[:focus]:`, but not the `:` in `ml-[length:3px]`), an `!` before or after, and a leading
// `-`. Then it reports each token that is:
// - a physical utility: `ml-`/`mr-`, `pl-`/`pr-`, `scroll-ml-`…, `left-`/`right-`, `text-left`,
//   `float-`/`clear-left`, `border-l`/`border-r` with any width or colour, `rounded-l-`/`-tl-`…,
//   `bg-`/`object-`/`mask-` positions (`bg-top-left`), `mask-l-`/`mask-r-`, `mask-radial-at-left`,
//   `bg-linear-to-l` with or without a `/` modifier, `touch-pan-left`, `break-before-left`;
// - a utility with no flow-relative form, which needs an `rtl:` variant instead: `origin-` and
//   `perspective-origin-` other than `center`, `top` and `bottom` (`origin-[left_top]`,
//   `origin-(--x)`), `translate-x-`, `scale-x-`, `skew-x-`, and the one-sided resize cursors;
// - any token whose `[…]` holds the word left or right: an arbitrary property
//   (`[margin-left:4px]`, `[text-align:right]`) or value (`bg-[left_top]`). A custom property's
//   name is not read (`[--panel-left:4px]`), only its value.
// Checked on 2026-10-13 against every class Tailwind 4.3.3 lists for the SPA's theme: it reports
// each one whose CSS sets only one side (left or right), and no other except the families above
// whose CSS names no side (`translate-x-`, `scale-x-`, `skew-x-`, the resize cursors).
//
// A hit inside a `//` or `/* */` comment is marked `(comment)`: most are prose (`right-aligns`),
// but a real class in a comment still generates CSS (`mr-auto` at `Modal.tsx:17`). Strings and
// regular expressions are skipped so that `"https://…"` is not a comment. A comment inside a
// template's `${…}`, or after an apostrophe in JSX text on the same line, counts as code: that
// reports more. The other way round, JSX text holding `//` (`<p>https://…</p>`) counts as a
// comment up to the line's end.
//
// It cannot see:
// - other files Tailwind reads: `@tailwindcss/vite` scans all of `web/` (Vite's root) except
//   files in `.gitignore`, `node_modules`, binary files, CSS files and lock files, so also
//   `web/index.html`, `package.json`, the `tsconfig` files and the SVGs. Run it on `web/src` and
//   read those by hand;
// - classes generated by `@source inline()` with braces (`ml-{1..2}`): it lists every
//   `@source inline(` line for a person to read;
// - classes built by joining strings (`'m' + side + '-4'`), which Tailwind cannot see either;
// - angles and arbitrary transforms (`bg-linear-45`, `rotate-*`, `translate-[4px_0]`,
//   `[transform:scaleX(-1)]`), which do not mirror but name no side;
// - JavaScript that assumes left to right (`scrollLeft` math, arrow keys, inline `scaleX`).
// It matches names, not CSS, so it also reports a token Tailwind would not compile
// (`right-to-left` outside a comment).
//
// Exit code: 1 when a class is found outside a comment, or an `@source inline(` line exists;
// 0 otherwise.
import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2];
if (!root) {
  console.error('Usage: node physical-scan.mjs <dir>');
  process.exit(2);
}

const side = '((top|bottom)-)?(left|right)(-(top|bottom))?';
const physical = [
  /^(m|p)[lr]-.+$/, // ml- mr- pl- pr-
  /^scroll-(m|p)[lr]-.+$/, // scroll-ml- scroll-pr- …
  /^(left|right)-.+$/, // left-4 right-px left-(--sidebar)
  /^text-(left|right)$/,
  /^(float|clear)-(left|right)$/,
  /^border-[lr](-.+)?$/, // border-l, border-l-2, border-l-ink, border-l-danger-500/50, border-l-(--c)
  /^rounded-([lr]|[tb][lr])(-.+)?$/,
  new RegExp(`^(bg|object|mask)-${side}$`), // bg-left bg-top-left object-left-bottom mask-right
  /^mask-[lr]-.+$/, // mask-l-from-4 mask-r-to-80%
  /^mask-radial-at-((top|bottom)-)?(left|right)$/,
  /^(bg|mask)-(linear|gradient)-to-(l|r|tl|tr|bl|br)(\/.+)?$/, // bg-linear-to-l/srgb
  /^touch-pan-(left|right)$/,
  /^break-(before|after)-(left|right)$/,
  // No flow-relative form: these need an `rtl:` variant.
  /^(perspective-)?origin-(?!(center|top|bottom)$).+$/, // origin-left origin-[left_top] origin-(--x)
  /^translate-x-.+$/,
  /^scale-x-.+$/,
  /^skew-x-.+$/,
  /^cursor-([ns]?[ew]|nesw|nwse)-resize$/,
];
const word = /(?<![a-z])(left|right)(?![a-z])/;

function isPhysical(base) {
  if (physical.some((re) => re.test(base))) return true;
  // An arbitrary property or value: read the inside of each `[…]`.
  for (const [, inside] of base.matchAll(/\[([^\]]*)\]/g)) {
    const value = inside.startsWith('--') ? inside.slice(inside.indexOf(':') + 1) : inside;
    if (word.test(value)) return true;
  }
  return false;
}

// Splits a token at each `:` outside `[…]` and `(…)`.
function splitVariants(t) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < t.length; i++) {
    const c = t[i];
    if (c === '[' || c === '(') depth++;
    else if ((c === ']' || c === ')') && depth > 0) depth--;
    else if (c === ':' && depth === 0) {
      parts.push(t.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(t.slice(start));
  return parts;
}

// Cuts a file into [token, offset] pairs. A space always ends a token; the other stop
// characters end one only outside `[…]`.
function tokens(text) {
  const out = [];
  const stop = /["'`{};,=<>$]/;
  let depth = 0;
  let start = -1;
  for (let i = 0; i <= text.length; i++) {
    const c = text[i];
    const space = c === undefined || /\s/.test(c);
    if (space || (depth === 0 && stop.test(c))) {
      if (start >= 0) out.push([text.slice(start, i), start]);
      start = -1;
      if (space) depth = 0;
      continue;
    }
    if (start < 0) start = i;
    if (c === '[') depth++;
    else if (c === ']' && depth > 0) depth--;
  }
  return out;
}

// Drops an unmatched `)` and what follows it (`ml-4)`), or what precedes an unmatched `(`
// (`cn(ml-4`).
function trimParens(t) {
  let depth = 0;
  for (let i = 0; i < t.length; i++) {
    if (t[i] === '(') depth++;
    else if (t[i] === ')' && depth-- === 0) return t.slice(0, i);
  }
  if (depth === 0) return t;
  let open = 0;
  for (let i = t.length - 1; i >= 0; i--) {
    if (t[i] === ')') open--;
    else if (t[i] === '(' && ++open > 0) return t.slice(i + 1);
  }
  return t;
}

// Whether a `/` at `i` starts a regular expression rather than a division or `</tag>`.
function regexCanStart(text, i) {
  let j = i - 1;
  while (j >= 0 && /\s/.test(text[j])) j--;
  if (j < 0) return true;
  if ('(,=:[!&|?{;+-*%~^>'.includes(text[j])) return true;
  const word = /[A-Za-z_$]+$/.exec(text.slice(Math.max(0, j - 10), j + 1));
  return word !== null && /^(return|typeof|case|do|else|in|of|void|yield|await|delete|throw|new)$/.test(word[0]);
}

// Marks which characters of a file are inside a comment. CSS has only `/* */`.
function commentMask(text, css) {
  const mask = new Uint8Array(text.length);
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    const next = text[i + 1];
    if (c === '/' && next === '*') {
      const end = text.indexOf('*/', i + 2);
      const stop = end < 0 ? text.length : end + 2;
      mask.fill(1, i, stop);
      i = stop;
    } else if (!css && c === '/' && next === '/') {
      const end = text.indexOf('\n', i);
      const stop = end < 0 ? text.length : end;
      mask.fill(1, i, stop);
      i = stop;
    } else if (c === '"' || c === "'" || c === '`') {
      // a string; `'` and `"` end at the line's end even when unclosed (JSX text)
      i++;
      while (i < text.length && text[i] !== c && (c === '`' || text[i] !== '\n')) {
        i += text[i] === '\\' ? 2 : 1;
      }
      i++;
    } else if (!css && c === '/' && regexCanStart(text, i)) {
      // a regular expression: skip it, so a quote or a backtick inside it starts nothing
      let inClass = false;
      i++;
      while (i < text.length && text[i] !== '\n' && (text[i] !== '/' || inClass)) {
        if (text[i] === '[') inClass = true;
        else if (text[i] === ']') inClass = false;
        i += text[i] === '\\' ? 2 : 1;
      }
      i++;
    } else {
      i++;
    }
  }
  return mask;
}

const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(entry.name)) files.push(p);
  }
})(root);

const hits = [];
const inlineSources = [];
for (const file of files.sort()) {
  const text = fs.readFileSync(file, 'utf8');
  const name = path.relative(root, file);
  const css = file.endsWith('.css');
  const mask = commentMask(text, css);
  const lineStarts = [0];
  for (let i = 0; i < text.length; i++) if (text[i] === '\n') lineStarts.push(i + 1);
  const lineOf = (offset) => {
    let line = 0;
    while (line + 1 < lineStarts.length && lineStarts[line + 1] <= offset) line++;
    return line + 1;
  };
  if (css) {
    text.split('\n').forEach((line, i) => {
      if (line.includes('@source inline(')) inlineSources.push(`${name}:${i + 1}\t${line.trim()}`);
    });
  }
  for (const [raw, offset] of tokens(text)) {
    const base = splitVariants(trimParens(raw)).pop().replace(/^!/, '').replace(/!$/, '').replace(/^-/, '');
    if (base && isPhysical(base)) hits.push({ where: `${name}:${lineOf(offset)}`, raw, comment: mask[offset] === 1 });
  }
}

for (const h of hits) console.log(`${h.where}\t${h.raw}${h.comment ? '\t(comment)' : ''}`);
for (const s of inlineSources) console.log(`${s}\t(@source inline: read by hand)`);
const inCode = hits.filter((h) => !h.comment).length;
console.log(`\n${inCode} in code, ${hits.length - inCode} in comments, ${inlineSources.length} @source inline() lines`);
process.exit(inCode > 0 || inlineSources.length > 0 ? 1 : 0);
